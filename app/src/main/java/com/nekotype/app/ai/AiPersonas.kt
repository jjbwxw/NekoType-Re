    fun byId(id: String): Persona? = ALL.firstOrNull { it.id == id }

    fun byName(name: String): Persona? = ALL.firstOrNull { it.name == name }

    /** 兜底人设：润色（列表第一个） */
    fun default(): Persona = ALL.first()

    /**
     * 按 AppPrefs.aiPromptMode 选出本次使用的提示词（永不返回空白提示词）：
     * 0 = 跟随当前预设人设（当前规则预设名 == 人设名 → 用对应提示词；否则润色）
     * 1 = 固定人设（aiPersonaId）
     * 2 = 自定义提示词（aiCustomPrompt 原文作为 system 提示词；为空则回落润色）
     */
    fun pick(): Persona = try {
        when (AppPrefs.aiPromptMode) {
            1 -> byId(AppPrefs.aiPersonaId) ?: default()
            2 -> {
                val custom = AppPrefs.aiCustomPrompt.trim()
                if (custom.isEmpty()) default() else Persona("custom", "自定义提示词", custom)
            }
            else -> byName(AppPrefs.activePresetName()) ?: default()
        }
    } catch (_: Throwable) {
        default()
    }
